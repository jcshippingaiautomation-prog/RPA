-- ============================================================
--  13: ชื่อที่ผู้ใช้ตั้งเองให้ Master
--
--  ผู้ใช้แจ้ง 10 ต.ค. 2569: "ชื่อ Master ใส่เป็นอักษรเฉพาะ User ตั้งเอง
--  แยกจากปัจจุบันที่เปลี่ยนไปเป็นชื่อ consignee"
--
--  ของเดิม `name` ถูกตั้งอัตโนมัติจากชื่อผู้รับ + สินค้า เช่น
--     "THANAKORN — AN LONG FOOD JOINT STOCK CORPORATION. · REFINED SOYBEAN OIL"
--  ซึ่งยาวและไม่ใช่คำที่ทีมเรียกกันจริง
--
--  `label` = ชื่อสั้นที่ผู้ใช้ตั้งเอง (เช่น "ALF ตู้น้ำมันเวียดนาม")
--  ใช้แสดงในหน้าคลัง Master แทน `name` ส่วน `name` ยังเก็บไว้ใช้อ้างอิง/ค้นหา
--
--  ⚠ ต้องรัน sql/11 และ sql/12 ก่อน · รันซ้ำได้
-- ============================================================
alter table public.declaration_templates
  add column if not exists label text;

comment on column public.declaration_templates.label is
  'ชื่อที่ผู้ใช้ตั้งเอง ใช้แสดงแทน name (name = ชื่ออัตโนมัติจากผู้รับ+สินค้า)';
